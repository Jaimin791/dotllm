/**
 * AI_PROJECT_CONTEXT.md generator
 */

import type { AnalysisResult } from '../types/index.js';
import { detectProjectType, generateFolderStructureString } from '../analyzers/file-tree.js';
import { getProjectDescription } from '../analyzers/config-parser.js';

/**
 * Generate AI_PROJECT_CONTEXT.md content
 */
export function generateContextMarkdown(analysis: AnalysisResult): string {
  const timestamp = new Date().toISOString().split('T')[0];
  const projectType = detectProjectType(analysis.projectRoot);
  const description = getProjectDescription(analysis.projectRoot);

  let markdown = `# AI Project Context

> Auto-generated by dotllm. DO NOT EDIT MANUALLY.
> Last updated: ${timestamp}

This document provides essential context for AI assistants to understand this codebase.
Use this as your source of truth for architecture decisions and constraints.

---

## Project Overview

**Name:** ${analysis.projectName}
**Type:** ${projectType}
`;

  if (description) {
    markdown += `**Description:** ${description}\n`;
  }

  // Languages and frameworks
  if (analysis.languages.length > 0) {
    markdown += `**Primary Languages:** ${analysis.languages.join(', ')}\n`;
  }
  if (analysis.frameworks.length > 0) {
    markdown += `**Frameworks:** ${analysis.frameworks.join(', ')}\n`;
  }
  if (analysis.packageManagers.length > 0) {
    markdown += `**Package Manager:** ${analysis.packageManagers.join(', ')}\n`;
  }
  if (analysis.isMonorepo) {
    markdown += `**Architecture:** Monorepo`;
    if (analysis.workspaces && analysis.workspaces.length > 0) {
      markdown += ` (${analysis.workspaces.length} workspaces)`;
    }
    markdown += '\n';
  }

  markdown += '\n---\n\n';

  // Repository structure
  markdown += `## Repository Structure

\`\`\`
${generateFolderStructureString(analysis.folderStructure, '', 3)}\`\`\`

`;

  // Folder responsibilities
  if (analysis.folderResponsibilities.length > 0) {
    markdown += `---

## Folder Responsibilities

| Path | Responsibility | Ownership |
|------|----------------|-----------|
`;
    for (const folder of analysis.folderResponsibilities.slice(0, 20)) {
      const ownership = folder.ownership || '—';
      markdown += `| \`${folder.path}\` | ${folder.responsibility} | ${ownership} |\n`;
    }
    markdown += '\n';
  }

  // Key dependencies
  const keyDeps = analysis.dependencies.filter((d) => !d.isDev).slice(0, 15);
  if (keyDeps.length > 0) {
    markdown += `---

## Key Dependencies

| Package | Version | Purpose |
|---------|---------|---------|
`;
    for (const dep of keyDeps) {
      const purpose = inferDependencyPurpose(dep.name);
      markdown += `| \`${dep.name}\` | ${dep.version} | ${purpose} |\n`;
    }
    markdown += '\n';
  }

  // Critical paths
  if (analysis.criticalPaths.length > 0) {
    markdown += `---

## Critical Paths (Handle with Care)

> [!CAUTION]
> These areas have significant blast radius. Changes require extra review.

| Path | Risk | Reason |
|------|------|--------|
`;
    for (const cp of analysis.criticalPaths) {
      markdown += `| \`${cp.path}\` | ${cp.risk} | ${cp.reason} |\n`;
    }
    markdown += '\n';
  }

  // Infrastructure
  if (analysis.infraTools.length > 0 || analysis.hasDocker || analysis.hasCICD) {
    markdown += `---

## Infrastructure & Deployment

`;
    if (analysis.infraTools.length > 0) {
      markdown += `**Infrastructure Tools:** ${analysis.infraTools.join(', ')}\n`;
    }
    if (analysis.hasDocker) {
      markdown += `**Containerization:** Docker\n`;
    }
    if (analysis.hasCICD) {
      markdown += `**CI/CD:** Configured (check \`.github/workflows\` or equivalent)\n`;
    }
    markdown += '\n';
  }

  // Development info
  markdown += `---

## Development

`;

  // Try to infer common scripts
  const scripts = inferDevelopmentScripts(analysis);
  if (scripts.length > 0) {
    markdown += `### Common Commands

\`\`\`bash
${scripts.join('\n')}
\`\`\`

`;
  }

  // Testing info
  if (analysis.hasTests) {
    markdown += `### Testing

- Test frameworks: ${analysis.testFrameworks.length > 0 ? analysis.testFrameworks.join(', ') : 'Detected'}
- Run tests with the appropriate command for your framework

`;
  }

  // What not to change
  markdown += `---

## What NOT to Change Casually

These areas require careful consideration and potentially team coordination:

`;

  const warnings = getChangeWarnings(analysis);
  for (const warning of warnings) {
    markdown += `1. **${warning.area}** - ${warning.reason}\n`;
  }

  // Footer
  markdown += `
---

## About This Document

This file was generated by [\`dotllm\`](https://www.npmjs.com/package/dotllm) to provide AI assistants with project-specific context.

To regenerate, run:
\`\`\`bash
npx dotllm
\`\`\`
`;

  return markdown;
}


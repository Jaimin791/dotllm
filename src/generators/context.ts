/**
 * Infer development scripts based on detected tools
 */
function inferDevelopmentScripts(analysis: AnalysisResult): string[] {
  const scripts: string[] = [];

  // Package manager based commands
  const pm = analysis.packageManagers[0];
  if (['npm', 'yarn', 'pnpm', 'bun'].includes(pm)) {
    const run = pm === 'npm' ? 'npm run' : pm;
    scripts.push(`# Install dependencies`);
    scripts.push(`${pm} install`);
    scripts.push('');
    scripts.push(`# Start development server`);
    scripts.push(`${run} dev`);

    if (analysis.hasTests) {
      scripts.push('');
      scripts.push(`# Run tests`);
      scripts.push(`${run} test`);
    }

    if (analysis.lintTools.length > 0) {
      scripts.push('');
      scripts.push(`# Lint code`);
      scripts.push(`${run} lint`);
    }
  } else if (pm === 'pip' || pm === 'poetry' || pm === 'pipenv') {
    scripts.push(`# Install dependencies`);
    if (pm === 'poetry') {
      scripts.push('poetry install');
    } else if (pm === 'pipenv') {
      scripts.push('pipenv install');
    } else {
      scripts.push('pip install -r requirements.txt');
    }
  } else if (pm === 'cargo') {
    scripts.push('# Build project');
    scripts.push('cargo build');
    scripts.push('');
    scripts.push('# Run project');
    scripts.push('cargo run');
  } else if (pm === 'go') {
    scripts.push('# Build project');
    scripts.push('go build');
    scripts.push('');
    scripts.push('# Run project');
    scripts.push('go run .');
  }

  return scripts;
}

/**
 * Get warnings about what not to change casually
 */
function getChangeWarnings(analysis: AnalysisResult): Array<{ area: string; reason: string }> {
  const warnings: Array<{ area: string; reason: string }> = [];

  // Always include auth warning if detected
  if (analysis.criticalPaths.some((cp) => cp.path.includes('auth'))) {
    warnings.push({
      area: 'Authentication flow',
      reason: 'Security critical - changes can expose vulnerabilities',
    });
  }

  // Database migrations
  if (analysis.criticalPaths.some((cp) => cp.path.includes('migration'))) {
    warnings.push({
      area: 'Database migrations',
      reason: 'Schema changes affect production data - coordinate with team',
    });
  }

  // Prisma schema
  if (analysis.databases.includes('prisma')) {
    warnings.push({
      area: 'Prisma schema',
      reason: 'Database schema changes require migrations and can break existing data',
    });
  }

  // Shared types in monorepo
  if (analysis.isMonorepo) {
    warnings.push({
      area: 'Shared packages/types',
      reason: 'Changes affect multiple apps in the monorepo',
    });
  }

  // Infrastructure
  if (analysis.hasInfraAsCode) {
    warnings.push({
      area: 'Infrastructure code (Terraform, etc.)',
      reason: 'Changes can affect production cloud resources',
    });
  }

  // CI/CD
  if (analysis.hasCICD) {
    warnings.push({
      area: 'CI/CD workflows',
      reason: 'Broken workflows can block deployments',
    });
  }

  // Package.json in libraries
  if (analysis.dependencies.length > 0) {
    warnings.push({
      area: 'Dependency versions',
      reason: 'Version changes can introduce breaking changes or vulnerabilities',
    });
  }

  return warnings;
}
